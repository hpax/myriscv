#!/usr/bin/perl

use strict;
use integer;

# Split a string into tokens; the string will not include quoted
# strings. This treats any sequence of non-word characters except brackets
# as a single token, which isn't really correct, but good enough
# for what we need.
sub toksplit($) {
    my($s) = @_;

    return grep { !/^\s*$/ } split(/(\s+|(?:\`\s*)?[\w\$\']+|[\(\)\{\}\[\]])/, $s);
}

# Read a single statement and break it into tokens
sub readstmt($) {
    my($fh) = @_;

    # 0: normal
    # 1: seen /
    # 2: // comment
    # 3: /* comment
    # 4: /* comment, seen *
    # 5: quoted string
    # 6: quoted string, seen \

    my @tok;
    my $s;
    my $c;
    my @pushback = ();
    my $state = 0;

    do {
	$c = pop(@pushback);
	$c = getc($fh) if (!defined($c));

	if ($state == 0) {
	    if ($c eq '/') {
		$state = 1;
	    } elsif ($c eq '"') {
		push(@tok, toksplit($s));
		$s = $c;
		$state = 5;
	    } elsif ($c eq ';') {
		push(@tok, toksplit($s), ';');
		undef $c;	# Terminate
	    } else {
		$s .= $c;
	    }
	} elsif ($state == 1) {
	    if ($c eq '/') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 2;
	    } elsif ($c eq '*') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 3;
	    } else {
		$s .= '/';
		push(@pushback, $c);
		$state = 0;
	    }
	} elsif ($state == 2) {
	    $state = 0 if ($c eq "\n");
	} elsif ($state == 3) {
	    $state = 4 if ($c eq '*');
	} elsif ($state == 4) {
	    $state = ($c eq '/') ? 0 : 3;
	} elsif ($state == 5) {
	    $s .= $c;
	    if ($c =~ /^\"?$/) {
		push(@tok, $s);
		undef $s;
		$state = 0;
	    } elsif ($c eq "\\") {
		$state = 6;
	    }
	} elsif ($state == 6) {
	    if ($c =~ /^\n?$/) {
		$s = substr($s, 0, -1);
	    } else {
		$s .= $c;
	    }
	    $state = 5;
	} else {
	    die;
	}
    } while (defined($c));

    return @tok;
}

# Find the parameter name: ignoring bracketed expressions, followed by = ;
sub paramname(@) {
    my $br = 0;
    my $n;
    foreach my $t (@_) {
	if (!$br && $t =~ /^[\=\;]$/) {
	    last;
	} elsif ($t eq '[') {
	    $br++;
	} elsif ($t eq ']') {
	    $br--;
	} elsif ($t =~ /^\w+$/) {
	    $n = $t;
	}
    }
    return $n;
}

# Strip the default value and ; from a token list
sub rawparam(@) {
    my @tok = ();
    foreach my $t (@_) {
	if ($t =~ /^[\=\;]$/) {
	    last;
	} else {
	    push(@tok, $t);
	}
    }
    return @tok;
}

my $what = '-vh';
if ($ARGV[0] =~ /^-/) {
    $what = shift @ARGV;
}

my @files = @ARGV;

my $TYPE_UNSIGNED = 0;
my $TYPE_SIGNED   = 1;
my $TYPE_STRING   = 2;

my @params;
my %types;

foreach my $f (@files) {
    my $fh;
    open($fh, '<', $f) or die "$0: $f: $!\n";

    my @tok;
    while (scalar(@tok = readstmt($fh))) {
	if ($tok[0] eq 'parameter') {
	    my @raw  = rawparam(@tok);
	    my $name = paramname(@raw);
	    my $type;
	    if (scalar(@raw) == 2) {
		# Just "parameter name = ..." -> integer
		$type = $TYPE_SIGNED;
	    } elsif (grep(/^string$/, @raw)) {
		$type = $TYPE_STRING;
		# This is for the Quartus type workaround hack
		foreach my $t (@tok) {
		    if ($t eq 'string') {
			$t = '`CONFIG_STRING_PARAM';
			last;
		    }
		}
	    } elsif (grep(/^signed$/, @raw)) {
		$type = $TYPE_SIGNED;
	    } elsif (grep(/^(int|integer)$/, @raw)) {
		$type = grep(/^unsigned$/, @raw)
		    ? $TYPE_UNSIGNED : $TYPE_SIGNED;
	    } else {
		$type = $TYPE_UNSIGNED;
	    }
	    $types{$name} = $type;

	    push(@params, [@tok]);
	} elsif (scalar(@tok)) {
	    print join(' ', @tok), "\n";
	}
    }
    close($fh);
}

if ($what eq '-dump') {
    my $pfx = 'MYRISCV_';
    print "// Dump the default or optional configuration specified\n\n";
    print "`include \"myriscv.vh\"\n\n";
    print "module dumpparams #(`CONFIG);\n";
    print " initial begin\n";
    print "  \$display(\"// Autogenerated from ", join(', ', @files), "\");\n";
    print "  \$display(\"\");\n";
    print "  \$display(\"#ifndef ${pfx}PARAMS_H\");\n";
    print "  \$display(\"#define ${pfx}PARAMS_H 1\");\n";
    print "  \$display(\"\");\n";

    @params = sort { paramname(@$a) cmp paramname(@$b) } @params;

    foreach my $px (@params) {
	my $p = paramname(@$px);
	my $type = $types{$p};
	my $fmt;
	if ($type == $TYPE_STRING) {
	    printf "  \$display(\"#define ${pfx}%-24s \\\"%s\\\"\", $p);\n", $p;
	} else {
	    print  "  if (!\$isunknown($p))\n";
	    printf "   if (\$size($p) < 4)\n";
	    printf "    \$display(\"#define ${pfx}%-24s %%d\", $p);\n", $p;
	    print  "   else\n";
	    printf "    \$display(\"#define ${pfx}%-24s %s\", $p);\n",
		$p, ($type == $TYPE_UNSIGNED) ? "0x%x" : "%0d";
	}
    }
    print "  \$display(\"\");\n";
    print "  \$display(\"#endif // ${pfx}PARAMS_H\");\n";
    print "  \$display(\"\");\n";
    # vvp insists on printing a final status line, this turns it into a
    # C comment.
    print "      \$write(\"// \");\n";
    print "      \$finish;\n";
    print "   end\n";
    print "endmodule\n";
} else {
    print "// Autogenerated from ", join(', ', @files), "\n\n";

    print "`ifndef _PARAMS_VH\n";
    print "`define _PARAMS_VH 1\n\n";

    # Work around a bug in Quartus with string parameters
    print "`ifdef ALTERA_RESERVED_QIS\n";
    print "`define CONFIG_STRING_PARAM\n";
    print "`else\n";
    print "`define CONFIG_STRING_PARAM string\n";
    print "`endif\n\n";

    print "// Use this macro in the module definition to declare global parameters\n";
    print "`define CONFIG";
    my $pfx = '';
    foreach my $px (@params) {
	my @p = @$px;
	pop(@p);			# Strip ;
	print $pfx, " \\\n\t", join(' ', @p);
	$pfx = ',';
    }
    print "\n\n";

    print "// Use this macro in module instantiation to pass down parameters\n";
    print "`define CFG";
    my $pfx = '';
    foreach my $px (@params) {
	my $p = paramname(@$px);
	print $pfx, " \\\n\t.$p ($p)";
	$pfx = ',';
    }
    print "\n";

    print "\n`endif\n";
}
