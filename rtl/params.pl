#!/usr/bin/perl

use strict;
use integer;

# Split a string into tokens; the string will not include quoted
# strings. This treats any sequence of non-word characters except brackets
# as a single token, which isn't really correct, but good enough
# for what we need.
sub toksplit($) {
    my($s) = @_;

    return grep { !/^\s*$/ } split(/(\s+|(?:\`\s*)?[\w\$\']+|[\(\)\{\}\[\]])/, $s);
}

# Read a single statement and break it into tokens
sub readstmt($) {
    my($fh) = @_;

    # 0: normal
    # 1: seen /
    # 2: // comment
    # 3: /* comment
    # 4: /* comment, seen *
    # 5: quoted string
    # 6: quoted string, seen \

    my @tok;
    my $s;
    my $c;
    my @pushback = ();
    my $state = 0;

    do {
	$c = pop(@pushback);
	$c = getc($fh) if (!defined($c));

	if ($state == 0) {
	    if ($c eq '/') {
		$state = 1;
	    } elsif ($c eq '"') {
		push(@tok, toksplit($s));
		$s = $c;
		$state = 5;
	    } elsif ($c eq ';') {
		push(@tok, toksplit($s), ';');
		undef $c;	# Terminate
	    } else {
		$s .= $c;
	    }
	} elsif ($state == 1) {
	    if ($c eq '/') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 2;
	    } elsif ($c eq '*') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 3;
	    } else {
		$s .= '/';
		push(@pushback, $c);
		$state = 0;
	    }
	} elsif ($state == 2) {
	    $state = 0 if ($c eq "\n");
	} elsif ($state == 3) {
	    $state = 4 if ($c eq '*');
	} elsif ($state == 4) {
	    $state = ($c eq '/') ? 0 : 3;
	} elsif ($state == 5) {
	    $s .= $c;
	    if ($c =~ /^\"?$/) {
		push(@tok, $s);
		undef $s;
		$state = 0;
	    } elsif ($c eq "\\") {
		$state = 6;
	    }
	} elsif ($state == 6) {
	    if ($c =~ /^\n?$/) {
		$s = substr($s, 0, -1);
	    } else {
		$s .= $c;
	    }
	    $state = 5;
	} else {
	    die;
	}
    } while (defined($c));

    return @tok;
}

# Find the parameter name: ignoring bracketed expressions, followed by = ;
sub paramname(@) {
    my $br = 0;
    my $n;
    foreach my $t (@_) {
	if (!$br && $t =~ /^[\=\;]$/) {
	    last;
	} elsif ($t eq '[') {
	    $br++;
	} elsif ($t eq ']') {
	    $br--;
	} elsif ($t =~ /^\w+$/) {
	    $n = $t;
	}
    }
    return $n;
}

# Strip the default value and ; from a token list
sub rawparam(@) {
    my @tok = ();
    foreach my $t (@_) {
	if ($t =~ /^[\=\;]$/) {
	    last;
	} else {
	    push(@tok, $t);
	}
    }
    return @tok;
}

my @files = @ARGV;

print "// Autogenerated from ", join(', ', @files), "\n\n";

print "`ifndef _PARAMS_VH\n";
print "`define _PARAMS_VH 1\n\n";

my @params;
foreach my $f (@files) {
    my $fh;
    open($fh, '<', $f) or die "$0: $f: $!\n";

    my @tok;
    while (scalar(@tok = readstmt($fh))) {
	if ($tok[0] eq 'parameter') {
	    push(@params, [@tok]);
	} elsif (scalar(@tok)) {
	    print join(' ', @tok), "\n";
	}
    }
    close($fh);
}

print "\n";

print "`define CONFIG" ;
my $pfx = '';
foreach my $px (@params) {
    my @p = @$px;
    pop(@p);			# Strip ;
    print $pfx, " \\\n\t", join(' ', @p);
    $pfx = ',';
}
print "\n";

print "`define CFG";
my $pfx = '';
foreach my $px (@params) {
    my $p = paramname(@$px);
    print $pfx, " \\\n\t.$p ($p)";
    $pfx = ',';
}
print "\n";

print "\n`endif\n";
