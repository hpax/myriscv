#!/usr/bin/perl
#
# Try to extract parameters or constants from a SystemVerilog file.
#

use strict;
use integer;

# Split a string into tokens; the string will not include quoted
# strings. This treats any sequence of non-word characters except brackets
# as a single token, which isn't really correct, but good enough
# for what we need.
sub toksplit($) {
    my($s) = @_;

    return grep { !/^\s*$/ } split(/(\s+|(?:\`\s*)?[\w\$\']+|[\(\)\{\}\[\]])/, $s);
}

# Read a single statement and break it into tokens
sub readstmt($) {
    my($fh) = @_;

    # 0: normal
    # 1: seen /
    # 2: // comment
    # 3: /* comment
    # 4: /* comment, seen *
    # 5: quoted string
    # 6: quoted string, seen \

    my @tok;
    my $s;
    my $c;
    my @pushback = ();
    my $state = 0;

    do {
	$c = pop(@pushback);
	$c = getc($fh) if (!defined($c));

	if ($state == 0) {
	    if ($c eq '/') {
		$state = 1;
	    } elsif ($c eq '"') {
		push(@tok, toksplit($s));
		$s = $c;
		$state = 5;
	    } elsif ($c =~ ';') {
		push(@tok, toksplit($s), ';');
		undef $c;	# Terminate
	    } else {
		$s .= $c;
	    }
	} elsif ($state == 1) {
	    if ($c eq '/') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 2;
	    } elsif ($c eq '*') {
		push(@tok, toksplit($s));
		undef $s;
		$state = 3;
	    } else {
		$s .= '/';
		push(@pushback, $c);
		$state = 0;
	    }
	} elsif ($state == 2) {
	    $state = 0 if ($c eq "\n");
	} elsif ($state == 3) {
	    $state = 4 if ($c eq '*');
	} elsif ($state == 4) {
	    $state = ($c eq '/') ? 0 : 3;
	} elsif ($state == 5) {
	    $s .= $c;
	    if ($c =~ /^\"?$/) {
		push(@tok, $s);
		undef $s;
		$state = 0;
	    } elsif ($c eq "\\") {
		$state = 6;
	    }
	} elsif ($state == 6) {
	    if ($c =~ /^\n?$/) {
		$s = substr($s, 0, -1);
	    } else {
		$s .= $c;
	    }
	    $state = 5;
	} else {
	    die;
	}
    } while (defined($c));

    return @tok;
}

# Find the parameter name: ignoring bracketed expressions, followed by = ;
sub paramname(@) {
    my $br = 0;
    my $n;
    foreach my $t (@_) {
	if (!$br && $t =~ /^[\=\;]$/) {
	    last;
	} elsif ($t eq '[') {
	    $br++;
	} elsif ($t eq ']') {
	    $br--;
	} elsif ($t =~ /^\w+$/) {
	    $n = $t;
	}
    }
    return $n;
}

# Strip the default value and ; from a token list
sub rawparam(@) {
    my @tok = ();
    foreach my $t (@_) {
	if ($t =~ /^[\=\;]$/) {
	    last;
	} else {
	    push(@tok, $t);
	}
    }
    return @tok;
}

my $what = '-vh';
my @include;
my $header;
my $pfx;
my $vguard;
my $output;

while ($ARGV[0] =~ /^-/) {
    my $opt = shift @ARGV;
    if ($opt =~ /^-(I|include)$/) {
	push(@include, shift @ARGV);
    } elsif ($opt eq '-prefix') {
	$pfx = shift @ARGV;
    } elsif ($opt eq '-guard') {
	$vguard = shift @ARGV;
    } elsif ($opt =~ /^-(o|out|output)$/) {
	$output = shift @ARGV;
    } elsif ($opt =~ /^-(dump|vh)$/) {
	$what = $opt;
    } elsif ($opt =~ /^--?$/) {
	last;
    } else {
	die "$0: unknown option: $opt\n";
    }
}

if (defined($output)) {
    open(STDOUT, '>', $output) or die "$0: $output: $!\n";
} else {
    $output = 'params.vh';	# For generating $vguard only
}
($vguard = uc($output)) =~ s/\W+/_/g unless (defined($vguard));
(my $cguard = $vguard) =~ s/_VH$/_H/;

my @files = @ARGV;

my $TYPE_UNSIGNED = 0;
my $TYPE_SIGNED   = 1;
my $TYPE_STRING   = 2;

my @params;
my %types;
my @enums;

foreach my $f (@files) {
    my $fh;
    open($fh, '<', $f) or die "$0: $f: $!\n";

    my @tok;
    while (scalar(@tok = readstmt($fh))) {
	if ($tok[0] =~ /^(parameter|const)$/) {
	    my @raw  = rawparam(@tok);
	    my $name = paramname(@raw);
	    my $type;
	    if (scalar(@raw) == 2) {
		# Just "parameter name = ..." -> integer
		$type = $TYPE_SIGNED;
	    } elsif (grep(/^string$/, @raw)) {
		$type = $TYPE_STRING;
		# This is for the Quartus type workaround hack
		foreach my $t (@tok) {
		    if ($t eq 'string') {
			$t = '`CONFIG_STRING_PARAM';
			last;
		    }
		}
	    } elsif (grep(/^signed$/, @raw)) {
		$type = $TYPE_SIGNED;
	    } elsif (grep(/^(int|integer)$/, @raw)) {
		$type = grep(/^unsigned$/, @raw)
		    ? $TYPE_UNSIGNED : $TYPE_SIGNED;
	    } else {
		$type = $TYPE_UNSIGNED;
	    }
	    $types{$name} = $type;

	    push(@params, [@tok]);
	} elsif ($tok[0] eq 'typedef') {
	    if ($tok[1] eq 'enum') {
		# It's an enum, should be dumped as constants
		push(@enums, $tok[-2]);
	    }
	}
    }
    close($fh);
}

if ($what eq '-dump') {
    print "// Dump the default or optional configuration specified\n\n";
    foreach my $vh (@include) {
	print "`include \"$vh\"\n";
    }
    print "\nmodule dumpparams #(`CONFIG);\n";
    print " initial begin\n";
    print "  \$display(\"// Autogenerated from ", join(', ', @files), "\");\n";
    print "  \$display(\"\");\n";
    print "  \$display(\"#ifndef $cguard\");\n";
    print "  \$display(\"#define $cguard 1\");\n";
    print "  \$display(\"\");\n";

    @params = sort { paramname(@$a) cmp paramname(@$b) } @params;

    # Dump constants and parameters
    foreach my $px (@params) {
	my $p = paramname(@$px);
	my $type = $types{$p};
	my $fmt;
	if ($type == $TYPE_STRING) {
	    printf "  \$display(\"#define ${pfx}%-24s \\\"%s\\\"\", $p);\n", $p;
	} else {
	    print  "  if (!\$isunknown($p))\n";
	    printf "   if (\$bits($p) < 16 || (($p | ~$p) < 0))\n";
	    printf "    \$display(\"#define ${pfx}%-24s %%d\", $p);\n", $p;
	    print  "   else\n";
	    printf "    \$display(\"#define ${pfx}%-24s 0x%%x\", $p);\n", $p;
	}
    }

    # Dump enumerations
    my $ei = 0;
    foreach my $en (@enums) {
	my $p = "_e_$en";
	print  "\n";
	print  "  begin\n";
	print  "    $en $p;\n";
	print  "    $p = $p.first();\n";
	print  "    \$display(\"\");\n";
	print  "    \$display(\"/* --- enum $en --- */\");\n";
	print  "    \$display(\"\");\n";
	print  "    do begin\n";
	print  "      if (!\$isunknown($p))\n";
	print  "       if (($p | ~$p) < 0)\n";
	print  "        \$display(\"#define ${pfx}%-24s %d\", $p.name(), $p);\n";
	print  "       else\n";
	print  "        \$display(\"#define ${pfx}%-24s 0x%x\", $p.name(), $p);\n";
	print  "      $p = $p.next();\n";
	print  "    end while ($p != $p.first());\n";
	print  "  end\n";
    }
    print "  \$display(\"\");\n";
    print "  \$display(\"#endif // $cguard\");\n";
    print "  \$display(\"\");\n";
    # vvp insists on printing a final status line, this turns it into a
    # C comment.
    print "      \$write(\"// \");\n";
    print "      \$finish;\n";
    print "   end\n";
    print "endmodule\n";
} elsif ($what eq '-vh') {
    # DO NOT sort the parameters in this file. Later parameters may
    # depend on earlier parameters.

    print "// Autogenerated from ", join(', ', @files), "\n\n";

    print "`ifndef $vguard\n";
    print "`define $vguard 1\n\n";

    # Work around a bug in Quartus with string parameters
    print "`ifdef ALTERA_RESERVED_QIS\n";
    print "`define CONFIG_STRING_PARAM\n";
    print "`else\n";
    print "`define CONFIG_STRING_PARAM string\n";
    print "`endif\n\n";

    print "// Use this macro in the module definition to declare global parameters\n";
    print "`define CONFIG";
    my $pfx = '';
    foreach my $px (@params) {
	my @p = @$px;
	pop(@p);			# Strip ;
	print $pfx, " \\\n\t", join(' ', @p);
	$pfx = ',';
    }
    print "\n\n";

    print "// Use this macro in module instantiation to pass down parameters\n";
    print "`define CFG";
    my $pfx = '';
    foreach my $px (@params) {
	my $p = paramname(@$px);
	print $pfx, " \\\n\t.$p ($p)";
	$pfx = ',';
    }
    print "\n";

    print "\n`endif // $vguard\n";
}
